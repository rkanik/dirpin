import fs from "node:fs";
import {
  ensureDirpinDir,
  loadPins,
} from "./store.js";
import {
  hooksCmdPath,
  hooksPs1Path,
  hooksShPath,
} from "./paths.js";

function toShPath(dir) {
  // Git Bash / MSYS prefer forward slashes
  return process.platform === "win32" ? dir.replace(/\\/g, "/") : dir;
}

function escapeShSingle(str) {
  return str.replace(/'/g, `'\"'\"'`);
}

function escapePsSingle(str) {
  return str.replace(/'/g, "''");
}

function escapeCmdDoskey(str) {
  return str.replace(/"/g, "");
}

export function writeHooks(pins = loadPins()) {
  ensureDirpinDir();
  const entries = Object.entries(pins).sort(([a], [b]) => a.localeCompare(b));

  const shLines = [
    "# Generated by dirpin — do not edit",
    ...entries.map(
      ([alias, dir]) =>
        `${alias}() { builtin cd '${escapeShSingle(toShPath(dir))}' || return; }`,
    ),
    "",
  ];
  fs.writeFileSync(hooksShPath(), shLines.join("\n"), "utf8");

  const ps1Lines = [
    "# Generated by dirpin — do not edit",
    ...entries.map(
      ([alias, dir]) =>
        `function ${alias} { Set-Location '${escapePsSingle(dir)}' }`,
    ),
    "",
  ];
  fs.writeFileSync(hooksPs1Path(), ps1Lines.join("\n"), "utf8");

  const cmdLines = [
    "@echo off",
    "REM Generated by dirpin — do not edit",
    ...entries.map(
      ([alias, dir]) =>
        `doskey ${alias}=cd /d "${escapeCmdDoskey(dir)}"`,
    ),
    "",
  ];
  fs.writeFileSync(hooksCmdPath(), cmdLines.join("\r\n"), "utf8");
}
